drop policy if exists "select_postal_code_cities" on public.postal_code_cities;
create policy "select_postal_code_cities"
  on public.postal_code_cities for select
  to authenticated using (true);

drop policy if exists "insert_postal_code_cities" on public.postal_code_cities;
create policy "insert_postal_code_cities"
  on public.postal_code_cities for insert
  to authenticated with check (public.a_role(array['admin']));

