alter table public.invoices
  add column if not exists source_system text not null default 'crm',
  add column if not exists external_invoice_id text,
  add column if not exists payment_data_complete boolean not null default true,
  add column if not exists credit_data_complete boolean not null default true,
  add column if not exists source_imported_at timestamptz,
  add column if not exists source_payload jsonb;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'invoices_source_system_check'
      and conrelid = 'public.invoices'::regclass
  ) then
    alter table public.invoices
      add constraint invoices_source_system_check
      check (source_system in ('crm', 'onify', 'reseau_glass'));
  end if;
end
$$;

